* Special Commands Dashboard (State user category)
*
* This dashboard is for state users within special commands at the state level to view and manage reports related to their command.
* Special commands at the state level have specific reporting and administrative protocols that must be followed.
* Their reporting template have unique form fields but still follows state user workflow.
* Special Command Users are under state_user category, have state_user role but operate within the special command structure at the state level.
* Special Command to be provisioned are:
*  1. Mfum Border Command
*  2. Idiroko Border Command
*  3. Seme Border Command
*  4. Lagos Passport Command
*  5. Murtala Muhammed Airport Command
*  6. Mallam Aminu Kano International Airport Command
* Workflow as structured steps:
*  1. Users submit reports to their designated desk admin.
*  2. Desk admin for each state reviews submitted reports for onward reporting to the special command admin.
*  3. Special command admin approves or requests revisions for reports.
*  4. Approved reports are forwarded to centralized HQ admin for further processing and record-keeping.
