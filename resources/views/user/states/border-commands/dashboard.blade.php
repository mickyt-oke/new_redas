* Border Commands Dashboard (State user category)
*
* This dashboard is for state users within border commands at the state level to view and manage reports related to their command.
* Border commands at the state level have specific reporting and administrative protocols that must be followed.
* Their reporting template have unique form fields but still follows state user workflow.
* Border Command Users are under state_user category, have state_user role but operate within the border command structure at the state level.
* Border Command to be provisioned are:
*  1. Mfum Border Command
*  2. Idiroko Border Command
*  3. Seme Border Command
* Workflow as structured steps:
*  1. Users submit reports to their designated desk admin.
*  2. Desk admin for each state reviews submitted reports for onward reporting to the border command admin.
*  3. Border command admin approves or requests revisions for reports.
*  4. Approved reports are forwarded to centralized HQ admin for further processing and record-keeping.
