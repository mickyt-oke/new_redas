* Zone Returns Creation (Zone user category)
*
* This page allows zone users to create and submit returns related to their zone.
* Zone users are under the zone_user category and have the zone_user role.
* The workflow for creating returns follows the structured steps defined for zone users.
*   The structured steps typically include filling out the return form, submitting it for review, and receiving confirmation of submission.`
* Workflow as structured steps:
*   1. Zone user fills out the return form with the data relevant to their zone.
*   2. Zone user submits the return form for zone_admin review.
*   3. The return is reviewed by the zonal commander alongside the state returns assigned to the zone.
*   4. Zone user receives confirmation of submission and notifications when necessary.
*
* Return template include sections as follows:
*   a. HRM data (Personnel Strength by Cadre, Trainings, Promotion, Transfers, Retirements, Study, Discipline)
*   b. Investigation and Compliance
*   c. Passport and Other Travel Documents
*   e. Works and Logistics
*   f. ICT and Cybersecurity
*   g. Border Management
*   h. Migration
*   i. Servicom
*   i. Finance and Account
*   j. ECOWAS and African Affairs
*   k. Visa and Residency
*   l. General Reports (Challenges, Situation, Incident or other reports)

